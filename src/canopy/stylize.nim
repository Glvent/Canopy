## Styling shortcuts work for built-ins and custom values with a style field.
import ./[style,text]
export style,text

func patchStyle*(item:Style, overlay:Style): Style = item.patch(overlay)
func patchStyle*[T](item:T, overlay:Style): T =
  result = item
  result.style = item.style.patch(overlay)
func withFg*[T](item:T, c:Color): T = item.patchStyle(initStyle().withFg(c))
func withFg*[T](item:T, c:ColorKind): T = item.withFg(color(c))
func withBg*[T](item:T, c:Color): T = item.patchStyle(initStyle().withBg(c))
func withBg*[T](item:T, c:ColorKind): T = item.withBg(color(c))
func withUnderlineColor*[T](item:T, c:Color): T = item.patchStyle(initStyle().withUnderlineColor(c))
func withAddModifier*[T](item:T, m:Modifiers): T = item.patchStyle(initStyle().withAddModifier(m))
func withAddModifier*[T](item:T, m:Modifier): T = item.withAddModifier({m})
func withRemoveModifier*[T](item:T, m:Modifiers): T = item.patchStyle(initStyle().withRemoveModifier(m))
func withRemoveModifier*[T](item:T, m:Modifier): T = item.withRemoveModifier({m})
func patchStyle*(content:string, overlay:Style): Span = initSpan(content,overlay)
func withFg*(content:string,c:Color): Span = initSpan(content,initStyle().withFg(c))
func withFg*(content:string,c:ColorKind): Span = content.withFg(color(c))
func withBg*(content:string,c:Color): Span = initSpan(content,initStyle().withBg(c))
func withBg*(content:string,c:ColorKind): Span = content.withBg(color(c))
template colorShortcuts(name,onName:untyped, kind:ColorKind) =
  func name*[T](item:T): auto = item.patchStyle(initStyle().withFg(kind))
  func onName*[T](item:T): auto = item.patchStyle(initStyle().withBg(kind))
colorShortcuts(black,onBlack,ColorKind.Black)
colorShortcuts(red,onRed,ColorKind.Red)
colorShortcuts(green,onGreen,ColorKind.Green)
colorShortcuts(yellow,onYellow,ColorKind.Yellow)
colorShortcuts(blue,onBlue,ColorKind.Blue)
colorShortcuts(magenta,onMagenta,ColorKind.Magenta)
colorShortcuts(cyan,onCyan,ColorKind.Cyan)
colorShortcuts(gray,onGray,ColorKind.Gray)
colorShortcuts(darkGray,onDarkGray,ColorKind.DarkGray)
colorShortcuts(lightRed,onLightRed,ColorKind.LightRed)
colorShortcuts(lightGreen,onLightGreen,ColorKind.LightGreen)
colorShortcuts(lightYellow,onLightYellow,ColorKind.LightYellow)
colorShortcuts(lightBlue,onLightBlue,ColorKind.LightBlue)
colorShortcuts(lightMagenta,onLightMagenta,ColorKind.LightMagenta)
colorShortcuts(lightCyan,onLightCyan,ColorKind.LightCyan)
colorShortcuts(white,onWhite,ColorKind.White)
template modifierShortcuts(name,negative:untyped, modifier:Modifier) =
  func name*[T](item:T): auto = item.patchStyle(initStyle().withAddModifier(modifier))
  func negative*[T](item:T): auto = item.patchStyle(initStyle().withRemoveModifier(modifier))
modifierShortcuts(bold,notBold,Modifier.Bold)
modifierShortcuts(dim,notDim,Modifier.Dim)
modifierShortcuts(italic,notItalic,Modifier.Italic)
modifierShortcuts(underlined,notUnderlined,Modifier.Underlined)
modifierShortcuts(reversed,notReversed,Modifier.Reversed)
modifierShortcuts(crossedOut,notCrossedOut,Modifier.CrossedOut)
modifierShortcuts(hidden,notHidden,Modifier.Hidden)
modifierShortcuts(slowBlink,notSlowBlink,Modifier.SlowBlink)
modifierShortcuts(rapidBlink,notRapidBlink,Modifier.RapidBlink)
func resetStyle*[T](item:T): auto = item.patchStyle(style.resetStyle())
