#!/usr/bin/env python3
"""Port Ratatui 0.30.2 symbol constants and exact border decomposition table.
Usage: python3 tools/block_generate_symbols.py [ratatui-source-root]
"""
import json,pathlib,re,sys
root=pathlib.Path(__file__).resolve().parents[1]
upstream=pathlib.Path(sys.argv[1]) if len(sys.argv)>1 else pathlib.Path("/tmp/canopy-upstream/ratatui-ratatui-v0.30.2")
sources=upstream/"ratatui-core/src/symbols"
def camel(s): return "".join(p.capitalize() for p in s.lower().split("_"))
def field(s):
    if s == "end": return "`end`"
    c=camel(s)
    return c[0].lower()+c[1:]
def quoted(s): return json.dumps(s,ensure_ascii=False)
values={}; sets={}; arrays={}
for module in ["bar","block","line","border","scrollbar","shade","half_block","marker","braille","pixel"]:
    source=(sources/f"{module}.rs").read_text()
    for name,value in re.findall(r'pub const (\w+): &(?:\'static )?str = "([^"]*)";',source): values[(module,name)]=value
    for name,value in re.findall(r"pub const (\w+): char = '(.*?)';",source): values[(module,name)]=value
    for name,body in re.findall(r"pub const (\w+): \[char; \d+\] = \[(.*?)\];",source,re.S): arrays[(module,name)]=re.findall(r"'(.*?)'",body)
    for name,body in re.findall(r"pub const (\w+): Set = Set \{(.*?)\};",source,re.S): sets[(module,name)]=body
    for name,line in re.findall(r"pub const (\w+): Set = from_line_set\(line::(\w+)\);",source): sets[(module,name)]="FROM:"+line
def resolve(module,expression):
    expression=expression.strip()
    if expression.startswith('"'): return json.loads(expression)
    if "::" in expression: module,expression=expression.split("::")
    if "." in expression:
        name,key=expression.split(".")
        return resolve_set(module,name)[key]
    return values[(module,expression)]
def resolve_set(module,name):
    body=sets[(module,name)]
    if isinstance(body,dict): return body
    if body.startswith("FROM:"):
        line=resolve_set("line",body[5:])
        result={k:line[k] for k in ["top_left","top_right","bottom_left","bottom_right"]}
        result.update(vertical_left=line["vertical"],vertical_right=line["vertical"],horizontal_top=line["horizontal"],horizontal_bottom=line["horizontal"])
    else:
        base=re.search(r"\.\.(\w+)",body)
        result=resolve_set(module,base[1]).copy() if base else {}
        for key,value in re.findall(r"(\w+):\s*([^,]+),",body): result[key]=resolve(module,value)
    sets[(module,name)]=result
    return result
path=root/"src/canopy/core/rendering/symbols.nim"
marker="# BEGIN GENERATED UPSTREAM SYMBOLS"
header=path.read_text().split(marker)[0].rstrip()
generated=[marker,"# Ratatui 0.30.2, MIT; generated by tools/block_generate_symbols.py.","const"]
for (module,name),value in values.items(): generated.append(f"  {camel(module)}{camel(name)}* = {quoted(value)}")
types={"bar":"BarSet","block":"BlockSet","line":"LineSet","border":"BorderSet","scrollbar":"ScrollbarSet"}
for module,name in sets:
    resolved=resolve_set(module,name)
    generated.append(f"  {camel(module)}{camel(name)}* = {types[module]}("+",".join(f"{field(k)}: {quoted(v)}" for k,v in resolved.items())+")")
for (module,name),items in arrays.items():
    generated.append(f"  {camel(name)}*: array[{len(items)},string] = [")
    for i in range(0,len(items),16): generated.append("    "+", ".join(map(quoted,items[i:i+16]))+",")
    generated.append("  ]")
path.write_text(header+"\n\n"+"\n".join(generated)+"\n")
source=(sources/"merge.rs").read_text()
entries=re.findall(r'"(.)" => \((\w+), (\w+), (\w+), (\w+)\)',source)
lines=["# Ratatui 0.30.2 box-drawing decomposition; MIT, see licenses/ratatui.txt.","# Generated by tools/block_generate_symbols.py.","const symbolParts: array["+str(len(entries))+", tuple[symbol:string, parts:Parts]] = ["]
for symbol,*parts in entries: lines.append("  ("+quoted(symbol)+", ["+", ".join("ls"+p for p in parts)+"]),")
lines.append("]")
(root/"src/canopy/internal/symbols/merge_table.nim").write_text("\n".join(lines)+"\n")
rust=['// Generated development oracle; reads constants from the pinned Rust library.','pub fn catalog()->serde_json::Value {','let mut result=serde_json::Map::new();']
nim=['# Generated adapter for independently evaluated Rust constants.','proc checkCatalog(catalog:JsonNode) =']
for module,name in values:
    label=camel(module)+camel(name)
    rust.append(f'result.insert("{label}".into(),serde_json::json!(ratatui::symbols::{module}::{name}.to_string()));')
    nim.append(f'  check catalog["{label}"].getStr == {label}')
for module,name in sets:
    label=camel(module)+camel(name)
    for key in resolve_set(module,name):
        rust.append(f'result.insert("{label}.{key}".into(),serde_json::json!(ratatui::symbols::{module}::{name}.{key}));')
        nim.append(f'  check catalog["{label}.{key}"].getStr == {label}.{field(key)}')
for module,name in arrays:
    label=camel(name)
    rust.append(f'result.insert("{label}".into(),serde_json::json!(ratatui::symbols::{module}::{name}.iter().map(char::to_string).collect::<Vec<_>>()));')
    nim.extend([f'  for i,v in {label}:',f'    check catalog["{label}"][i].getStr == v'])
rust.extend(['serde_json::Value::Object(result)','}'])
(root/'tools/block_symbol_catalog.rs').write_text('\n'.join(rust)+'\n')
(root/'tests/block_symbol_catalog.nim').write_text('\n'.join(nim)+'\n')
print(f"Generated symbol catalog and {len(entries)} exact box-drawing decompositions")
