#!/usr/bin/env python3
"""Regenerate checked-in Nim Unicode properties from the exact pinned Rust crates.
Development only: Python 3 + rustc + downloaded crates; runtime/tests need Nim only.
Usage: python3 tools/unicode/generate.py [Cargo registry source directory]
"""
import json, pathlib, re, shutil, subprocess, sys, tempfile
root = pathlib.Path(__file__).resolve().parents[2]
registry = pathlib.Path(sys.argv[1]) if len(sys.argv)>1 else next((pathlib.Path.home()/".cargo/registry/src").glob("*"))
seg = registry/"unicode-segmentation-1.13.3"
width = registry/"unicode-width-0.2.2"
out = root/"src/canopy/internal/unicode/tables.nim"
source = """
#[allow(dead_code, non_snake_case)] #[path=SEG] mod seg;
#[allow(dead_code)] mod width {
include!(WIDTH);
pub fn property(c: char) -> (u8,u16,u8) {
let (w,i) = lookup_width(c);
(w,i.0, (starts_emoji_presentation_seq(c) as u8)
| ((starts_non_ideographic_text_presentation_seq(c) as u8)<<1)
| ((is_emoji_modifier_base(c) as u8)<<2)
| ((is_transparent_zero_width(c) as u8)<<3)
| ((is_ligature_transparent(c) as u8)<<4))
}}
fn main() {
let mut last = (255,65535,255,255,255); let mut start = 0;
for cp in 0..=0x110000 {
let p = if let Some(c) = char::from_u32(cp) {
let (w,i,f) = width::property(c);
(w,i,f,seg::grapheme::grapheme_category(c).2 as u8,
(seg::derived_property::InCB_Extend(c) as u8) | ((seg::is_incb_linker(c) as u8)<<1))
} else {(1,0,0,0,0)};
if p != last || cp == 0x110000 {
if cp > 0 {println!("  ({}, {}, {}, {}, {}, {}, {}),", start,cp-1,last.0,last.1,last.2,last.3,last.4);}
start = cp; last = p;
}
}
}
""".replace("SEG", json.dumps(str(seg/"src/tables.rs"))).replace("WIDTH", json.dumps(str(width/"src/tables.rs")))
with tempfile.TemporaryDirectory() as temp:
    temp = pathlib.Path(temp)
    (temp/"generate.rs").write_text(source)
    subprocess.run(["rustc","--edition=2021","-Awarnings",str(temp/"generate.rs"),"-o",str(temp/"generate")],check=True)
    data = subprocess.check_output([str(temp/"generate")],text=True)
header = """# Generated by tools/unicode/generate.py. Do not edit.
# unicode-segmentation 1.13.3 / unicode-width 0.2.2; Unicode 17.0.0.
# Derived from Rust Project Developers tables, MIT or Apache-2.0.
# See licenses/unicode/ for complete upstream notices.
type UnicodeProperty* = tuple[first,last,width,info,flags,category,incb:int]
const unicodeProperties*: array[COUNT, UnicodeProperty] = [
""".replace("COUNT",str(len(data.splitlines())))
out.write_text(header+data+"]\n")
constants = re.findall(r"const ([A-Z_0-9]+): Self = Self\((0b[01_]+|0)\);",(width/"src/tables.rs").read_text())
(root/"src/canopy/internal/unicode/widthinfo.nim").write_text("# Generated from unicode-width 0.2.2; see licenses/unicode/.\nconst\n"+"".join(f"  wi{name}* = {value}\n" for name,value in constants))
for crate in (seg,width):
    target=root/"licenses/unicode"/crate.name
    target.mkdir(parents=True,exist_ok=True)
    for name in ("LICENSE-MIT","LICENSE-APACHE","COPYRIGHT"):
        shutil.copyfile(crate/name,target/name)
print(f"Generated {len(data.splitlines())} property ranges")
